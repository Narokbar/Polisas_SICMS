function getCurrentLanguage() {
    return localStorage.getItem("selectedLanguage") || "English";
}

function changeLanguage(language) {
    const selected = translations[language];
    if (!selected) return;

    const setText = (id, value) => {
        const element = document.getElementById(id);
        if (element) element.textContent = value;
    };

    const setHTML = (id, value) => {
        const element = document.getElementById(id);
        if (element) element.innerHTML = value;
    };

    const setPlaceholder = (id, value) => {
        const element = document.getElementById(id);
        if (element) element.placeholder = value;
    };

    setHTML("welcomeTitle", selected.welcomeTitle);
    setText("searchTitle", selected.searchTitle);
    setPlaceholder("searchInput", selected.searchPlaceholder);
    setText("quickAccessTitle", selected.quickAccessTitle);
    setText("announcementTitle", selected.announcementTitle);
    setText("result", selected.searchStart);
    setText("logoutBtn", selected.logout);
        // Student Enquiry Form
    const enquiryTitle = document.querySelector("#enquiryPanel .title");
    if (enquiryTitle) enquiryTitle.textContent = selected.enquiryTitle;

    const enquiryDescription = document.querySelector("#enquiryPanel .enquiry-container > p");
    if (enquiryDescription) enquiryDescription.textContent = selected.enquiryDescription;

    const enquiryLabels = {
        enquiryName: selected.enquiryName,
        enquiryStudentID: selected.enquiryStudentID,
        enquiryTopic: selected.enquiryTopic,
        enquiryQuestion: selected.enquiryQuestion
    };

    Object.entries(enquiryLabels).forEach(([id, text]) => {
        const label = document.querySelector(
            `#enquiryPanel label[for="${id}"]`
        );

        if (label) label.textContent = text;
    });

    const enquiryNameInput = document.getElementById("enquiryName");
    if (enquiryNameInput) {
        enquiryNameInput.placeholder = selected.enquiryNamePlaceholder;
    }

    const enquiryIDInput = document.getElementById("enquiryStudentID");
    if (enquiryIDInput) {
        enquiryIDInput.placeholder = selected.enquiryStudentIDPlaceholder;
    }

    const enquiryQuestionInput = document.getElementById("enquiryQuestion");
    if (enquiryQuestionInput) {
        enquiryQuestionInput.placeholder = selected.enquiryQuestionPlaceholder;
    }

    const enquiryTopicSelect = document.getElementById("enquiryTopic");

    if (enquiryTopicSelect) {
        const topicTranslations = {
            "": selected.enquiryTopicDefault,
            "Registration": selected.registration,
            "Fees": selected.enquiryFees,
            "Hostel": selected.hostel,
            "Transcript": selected.transcript,
            "SPMP": "SPMP",
            "Academic": selected.enquiryAcademic,
            "Other": selected.enquiryOther
        };

        Array.from(enquiryTopicSelect.options).forEach(option => {
            if (Object.prototype.hasOwnProperty.call(
                topicTranslations, option.value
            )) {
                option.textContent = topicTranslations[option.value];
            }
        });
    }

    const enquirySubmitButton = document.querySelector(
        "#enquiryForm .enquiry-submit"
    );

    if (enquirySubmitButton) {
        enquirySubmitButton.innerHTML =
            `<i class="fa-solid fa-paper-plane"></i> ${selected.enquirySubmit}`;
    }

    const enquiryBackButton = document.getElementById("closeEnquiry");
    if (enquiryBackButton) {
        enquiryBackButton.textContent = selected.enquiryBack;
    }

    // Translate an existing enquiry status message
    const enquiryStatus = document.getElementById("enquiryStatus");

    if (enquiryStatus && enquiryStatus.dataset.messageType) {
        const messageType = enquiryStatus.dataset.messageType;

        if (messageType === "success") {
            enquiryStatus.textContent = selected.enquirySuccess;
        } else if (messageType === "required") {
            enquiryStatus.textContent = selected.enquiryRequired;
        }
    }

    document.querySelectorAll(".card").forEach(card => {
        const heading = card.querySelector("h3");
        const key = card.dataset.search;
        if (heading && selected[key]) heading.textContent = selected[key];
    });

    // FAQ
    setText("faqTitle", selected.faqTitle);

    document.querySelectorAll(".faq-item").forEach((item, index) => {
        const question = item.querySelector(".faq-question");
        const answer = item.querySelector(".faq-answer p");

        if (question && selected.faqQuestions[index]) {
            const plus = question.querySelector("span");
            question.textContent = selected.faqQuestions[index];

            if (plus) {
                question.appendChild(plus);
            } else {
                const span = document.createElement("span");
                span.textContent = "+";
                question.appendChild(span);
            }
        }

        if (answer && selected.faqAnswers[index]) {
            answer.textContent = selected.faqAnswers[index];
        }
    });

    // Counter booking
    const bookingHeadings = document.querySelectorAll(".booking-section .title");
    if (bookingHeadings[0]) bookingHeadings[0].textContent = selected.bookingTitle;

    const bookingForm = document.querySelector(".booking-form");
    if (bookingForm) {
        const heading = bookingForm.querySelector("h2");
        const description = bookingForm.querySelector("p:not(.booking-error)");
        if (heading) heading.textContent = selected.bookingFormTitle;
        if (description) description.textContent = selected.bookingDescription;
    }

    const labels = {
        bookingService: selected.selectService,
        bookingDate: selected.selectDate,
        bookingTime: selected.selectTime
    };

    Object.entries(labels).forEach(([id, value]) => {
        const label = document.querySelector(`label[for="${id}"]`);
        if (label) label.textContent = value;
    });

    const service = document.getElementById("bookingService");
    if (service) {
        const options = [
            ["", selected.selectServiceOption],
            ["Student Registration", selected.studentRegistration],
            ["Transcript", selected.transcript],
            ["Fees", selected.payment],
            ["Hostel", selected.hostel],
            ["Student Affairs", selected.studentAffairs],
            ["Other", selected.other]
        ];

        options.forEach(([value, text]) => {
            const option = service.querySelector(`option[value="${value}"]`);
            if (option) option.textContent = text;
        });
    }

    const time = document.getElementById("bookingTime");
    if (time) {
        const option = time.querySelector('option[value=""]');
        if (option) option.textContent = selected.selectTimeOption;
    }

    setText("bookCounterBtn", selected.bookAppointment);
    setText("bookingResult", selected.noBooking);

    const placeholder = document.querySelector(".booking-placeholder p");
    if (placeholder) placeholder.textContent = selected.bookingInfo;

    // Location
    const locationTitle = document.querySelector(".location-section .title");
    if (locationTitle) locationTitle.textContent = selected.findUs;

    const locationDescription = document.querySelector(".location-info p:nth-of-type(2)");
    if (locationDescription) locationDescription.textContent = selected.locationDescription;

    const directions = document.querySelector(".direction-btn");
    if (directions) directions.textContent = selected.directions;

    // Announcements
    const track = document.querySelector(".announcement-track");
    if (track) {
        track.innerHTML = selected.announcementItems
            .map(item => item.replace(/&/g, "&amp;"))
            .join(" &nbsp;&nbsp; | &nbsp;&nbsp; ");
    }

    // Chatbot
    const attention = document.querySelector(".ai-attention small");
    if (attention) attention.textContent = selected.aiNeedHelp;

    const chatTitle = document.querySelector(".chat-header > div");
    if (chatTitle) chatTitle.textContent = selected.aiTitle;

    const chatInput = document.getElementById("chatInput");
    if (chatInput) chatInput.placeholder = selected.chatPlaceholder;

    const botMessage = document.querySelector("#chatBody .bot-message");
    if (botMessage) {
        const items = language === "Bahasa Melayu"
            ? ["Pendaftaran", "Yuran", "Asrama", "Transkrip", "SPMP", "Kalendar Akademik"]
            : ["Registration", "Fees", "Hostel", "Transcript", "SPMP", "Academic Calendar"];

        botMessage.innerHTML =
            `${selected.aiHello}<br><br>${selected.aiIntro}<br><br>${selected.aiHelp}<br><br>` +
            items.map(item => `✅ ${item}`).join("<br><br>") +
            `<br><br>${selected.aiClosing}`;
    }

    // Chat suggestions
    const suggestionLabels = language === "Bahasa Melayu"
        ? ["Pendaftaran", "Yuran", "Asrama", "SPMP"]
        : ["Registration", "Fees", "Hostel", "SPMP"];

    document.querySelectorAll(".chat-suggestion button").forEach((button, index) => {
        if (suggestionLabels[index]) button.textContent = suggestionLabels[index];
    });

    // Footer
    const footer = document.querySelector("footer");
    if (footer) footer.textContent = selected.footer;

    document.documentElement.lang = language === "Bahasa Melayu" ? "ms" : "en";
    localStorage.setItem("selectedLanguage", language);
}

const languageSelector = document.getElementById("language");

if (languageSelector) {
    languageSelector.addEventListener("change", function () {
        changeLanguage(this.value);
    });

    const savedLanguage = getCurrentLanguage();
    languageSelector.value = savedLanguage;
    changeLanguage(savedLanguage);
}
